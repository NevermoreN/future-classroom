//! Voice application/storage boundary. Request decoders cannot manufacture a
//! verified upload; trusted preparation checks the complete canonical WAV and
//! flushes its controlled object before producing this proof.
use fc_domain::{auth::ActorContext, ids::*, voice::*};
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum VoiceRepositoryError {
    Domain(VoiceError),
    Unavailable,
    Faulted,
    IdempotencyConflict,
    DocumentTooLarge,
}
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct VoiceSubmitRequest {
    pub command_id: CommandId,
    pub asset_id: VoiceAssetId,
    pub expected_asset_revision: Revision,
    pub class_id: ClassId,
    pub repeat_total: u8,
}
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct VoiceCancelRequest {
    pub command_id: CommandId,
    pub job_id: VoiceJobId,
    pub expected_revision: Revision,
}
pub trait VoicePreparation {
    type Input;
    /// Must use the supplied server-owned reservation ID and stream/validate the
    /// real bytes. Paths, owner and hashes from the HTTP body are never evidence.
    fn prepare(
        &mut self,
        input: Self::Input,
        reservation: &VoiceAsset,
    ) -> Result<VoicePcmMetadata, VoiceRepositoryError>;
}
/// No Deserialize, Clone or public constructor. Composition runs preparation on
/// a bounded worker and commits this proof on the existing single writer.
pub struct PreparedVoiceUpload {
    reservation: VoiceAsset,
    pcm: VoicePcmMetadata,
}
impl PreparedVoiceUpload {
    pub fn reservation(&self) -> &VoiceAsset {
        &self.reservation
    }
    pub fn pcm(&self) -> &VoicePcmMetadata {
        &self.pcm
    }
    pub fn into_parts(self) -> (VoiceAsset, VoicePcmMetadata) {
        (self.reservation, self.pcm)
    }
}
pub fn prepare_voice_upload<P: VoicePreparation>(
    preparation: &mut P,
    input: P::Input,
    reservation: VoiceAsset,
) -> Result<PreparedVoiceUpload, VoiceRepositoryError> {
    if reservation.state != VoiceAssetState::Reserved
        || reservation.pcm.is_some()
        || reservation.charged_bytes != MAX_WAV_BYTES
    {
        return Err(VoiceRepositoryError::Domain(VoiceError::InvalidState));
    }
    let pcm = preparation.prepare(input, &reservation)?;
    pcm.validate().map_err(VoiceRepositoryError::Domain)?;
    Ok(PreparedVoiceUpload { reservation, pcm })
}
/// Authenticated results redact `VoiceJob::authorization`. Retries return the
/// same task at its current durable state, never a stored QUEUED response and
/// never a second playback. Terminal results expire after 24 hours / 100 audits.
pub trait VoiceRepository {
    /// ID is generated by trusted composition (CSPRNG), never accepted as a
    /// client-selected file path. This reserves quota before reading the body.
    fn reserve_voice_upload(
        &self,
        id: VoiceAssetId,
        class_id: ClassId,
        actor: &ActorContext,
    ) -> Result<VoiceAsset, VoiceRepositoryError>;
    fn publish_voice_upload(
        &self,
        prepared: PreparedVoiceUpload,
        actor: &ActorContext,
    ) -> Result<VoiceAsset, VoiceRepositoryError>;
    fn submit_voice(
        &self,
        request: VoiceSubmitRequest,
        actor: &ActorContext,
    ) -> Result<VoiceJob, VoiceRepositoryError>;
    fn voice_job(
        &self,
        id: VoiceJobId,
        actor: &ActorContext,
    ) -> Result<VoiceJob, VoiceRepositoryError>;
    fn cancel_voice(
        &self,
        request: VoiceCancelRequest,
        actor: &ActorContext,
    ) -> Result<VoiceJob, VoiceRepositoryError>;
}
